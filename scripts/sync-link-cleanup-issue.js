#!/usr/bin/env node

/**
 * Render a Check Links report into a GitHub issue body and either create
 * a new "auto-link-cleanup" issue, update the most recent open one, or
 * close the open queue issue when the report is empty.
 *
 * Reads the issues array written by scripts/check-links.js (path comes from
 * env LINK_ISSUES_FILE, defaults to /tmp/link-issues.json). A missing file
 * or empty array is treated as a green report: any open auto-link-cleanup
 * issue whose title matches the auto queue is closed. Unrelated human
 * issues are never closed. Transient `error` statuses stay on the
 * create/update path and are listed as API errors, not as missing repos.
 *
 * Requires: gh CLI authenticated; repo permissions issues: write.
 */

const fs = require('fs');
const { execFileSync } = require('child_process');

const LABEL = 'auto-link-cleanup';
const LABEL_COLOR = 'fbca04';
const LABEL_DESC = 'Automated repository link cleanup queue';
const ISSUE_FILE = process.env.LINK_ISSUES_FILE || '/tmp/link-issues.json';
const CLEANUP_TITLE_RE = /^\[auto\] Repository link cleanup /i;

function gh(args, opts = {}) {
	return execFileSync('gh', args, { encoding: 'utf-8', stdio: opts.stdio ?? ['ignore', 'pipe', 'inherit'] });
}

function ensureLabel() {
	try {
		gh(['label', 'create', LABEL, '--color', LABEL_COLOR, '--description', LABEL_DESC], { stdio: ['ignore', 'pipe', 'pipe'] });
	} catch {
		// label already exists -- idempotent
	}
}

function findOpenCleanupIssues() {
	const out = gh(['issue', 'list', '--label', LABEL, '--state', 'open', '--limit', '20', '--json', 'number,createdAt,title,labels']);
	const list = JSON.parse(out || '[]');
	const cleanup = list.filter(issue => {
		const labels = Array.isArray(issue.labels) ? issue.labels.map(l => (typeof l === 'string' ? l : l.name)) : [];
		return labels.includes(LABEL) && CLEANUP_TITLE_RE.test(issue.title || '');
	});
	cleanup.sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1));
	return cleanup;
}

function findOpenIssueNumber() {
	const list = findOpenCleanupIssues();
	if (list.length === 0) return null;
	return list[0].number;
}

function runUrl() {
	return process.env.GITHUB_SERVER_URL && process.env.GITHUB_REPOSITORY && process.env.GITHUB_RUN_ID
		? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${process.env.GITHUB_RUN_ID}`
		: null;
}

function renderBody(issues, url) {
	const failures = issues.filter(i => ['not_found', 'archived', 'disabled'].includes(i.status));
	const redirects = issues.filter(i => i.status === 'redirected');
	const errors = issues.filter(i => i.status === 'error');

	const lines = [];
	lines.push('Check Links found ' + issues.length + ' repository link(s) that need attention.');
	lines.push('');
	lines.push('@cursoragent please open a PR that:');
	lines.push('1. for each **redirected** entry: update `data/projects.json` so its `repo` field points at the new location (and update `maintainer` if the owning org changed);');
	lines.push('2. for each **failure** (404 / archived / disabled): remove the entry from `data/projects.json`, unless it is a clear case of being replaced by another already-listed project, in which case just remove the duplicate;');
	lines.push('3. regenerate the README via `node scripts/generate-readme.js`;');
	lines.push('4. verify with `node scripts/check-links.js` that 0 failures remain (redirect warnings are tolerable but prefer to clean them too).');
	lines.push('');
	if (failures.length > 0) {
		lines.push('## Failures (remove or replace)');
		lines.push('');
		for (const i of failures) {
			lines.push('- [' + i.status + '] **' + i.name + '** (`' + i.repo + '`)' + (i.error ? ' -- ' + i.error : ''));
		}
		lines.push('');
	}
	if (redirects.length > 0) {
		lines.push('## Redirected (rewrite repo field)');
		lines.push('');
		for (const i of redirects) {
			lines.push('- **' + i.name + '**: `' + i.repo + '` -> `' + i.target + '`');
		}
		lines.push('');
	}
	if (errors.length > 0) {
		lines.push('## API errors (transient, will be re-checked next run)');
		lines.push('');
		for (const i of errors) {
			lines.push('- **' + i.name + '** (`' + i.repo + '`) -- ' + (i.error || 'unknown'));
		}
		lines.push('');
	}
	lines.push('---');
	lines.push('');
	lines.push('Generated by `Check Links` workflow on ' + new Date().toISOString().slice(0, 10) + (url ? ' ([run](' + url + '))' : '') + '. This issue is automatically refreshed on every schedule run; close it once the cleanup PR is merged.');
	return lines.join('\n');
}

function renderResolvedBody(url) {
	const date = new Date().toISOString().slice(0, 10);
	return [
		'Check Links found 0 repository link(s) that need attention.',
		'',
		'Previously reported failures and redirects have been cleared. This issue is closed automatically.',
		'',
		'---',
		'',
		'Resolved by `Check Links` workflow on ' + date + (url ? ' ([run](' + url + '))' : '') + '.',
	].join('\n');
}

function closeComment(url) {
	const date = new Date().toISOString().slice(0, 10);
	return 'Check Links found 0 repository link issues on ' + date + (url ? ' ([run](' + url + '))' : '') + '. The cleanup queue is empty, so this issue is being closed automatically.';
}

function loadIssues() {
	if (!fs.existsSync(ISSUE_FILE)) {
		console.log('No issues file at ' + ISSUE_FILE + ', treating as 0 link issues.');
		return [];
	}
	const issues = JSON.parse(fs.readFileSync(ISSUE_FILE, 'utf-8'));
	if (!Array.isArray(issues)) {
		console.error('Issues file is not an array: ' + ISSUE_FILE);
		process.exit(1);
	}
	return issues;
}

function closeOpenCleanupIssues(url) {
	const open = findOpenCleanupIssues();
	if (open.length === 0) {
		console.log('No open ' + LABEL + ' issue to close.');
		return;
	}

	const title = '[auto] Repository link cleanup resolved (' + new Date().toISOString().slice(0, 7) + ')';
	const body = renderResolvedBody(url);
	const comment = closeComment(url);

	if (process.env.LINK_ISSUE_DRY_RUN === '1') {
		for (const issue of open) {
			console.log('DRY RUN -- would close issue #' + issue.number + ' (' + issue.title + ')');
		}
		console.log('Title: ' + title);
		console.log('Comment:');
		console.log(comment);
		console.log('Body:');
		console.log(body);
		return;
	}

	for (const issue of open) {
		console.log('Closing issue #' + issue.number + ' (queue empty)');
		execFileSync('gh', ['issue', 'edit', String(issue.number), '--title', title, '--body', body], { stdio: 'inherit' });
		execFileSync('gh', ['issue', 'close', String(issue.number), '--reason', 'completed', '--comment', comment], { stdio: 'inherit' });
	}
}

function createOrUpdateIssue(issues, url) {
	const body = renderBody(issues, url);
	const month = new Date().toISOString().slice(0, 7);
	const title = `[auto] Repository link cleanup needed (${month})`;

	if (process.env.LINK_ISSUE_DRY_RUN === '1') {
		const existing = findOpenIssueNumber();
		console.log('DRY RUN -- would ' + (existing ? 'update issue #' + existing : 'create new issue') + ':');
		console.log('Title: ' + title);
		console.log('Body:');
		console.log(body);
		return;
	}

	ensureLabel();

	const existing = findOpenIssueNumber();
	if (existing) {
		console.log('Updating existing issue #' + existing);
		execFileSync('gh', ['issue', 'edit', String(existing), '--title', title, '--body', body], { stdio: 'inherit' });
		execFileSync('gh', ['issue', 'comment', String(existing), '--body', 'Refreshed by Check Links run on ' + new Date().toISOString().slice(0, 10) + '.'], { stdio: 'inherit' });
	} else {
		console.log('Creating new issue.');
		execFileSync('gh', ['issue', 'create', '--title', title, '--label', LABEL, '--body', body], { stdio: 'inherit' });
	}
}

function main() {
	const issues = loadIssues();
	const url = runUrl();

	if (issues.length === 0) {
		closeOpenCleanupIssues(url);
		return;
	}

	createOrUpdateIssue(issues, url);
}

main();
